#!/usr/bin/env python3
"""
Pre-build script for PlatformIO
- Increments VERSION_PATCH in src/Config.h
- Captures current Git commit hash
- Generates GitVersion.h with commit hash

This script is called by PlatformIO's extra_scripts mechanism.
"""

import os
import re
import subprocess
from pathlib import Path

# PlatformIO Import
Import("env")

def get_git_commit_hash(project_dir):
    """Get short commit hash from Git"""
    try:
        result = subprocess.run(
            ['git', 'rev-parse', '--short', 'HEAD'],
            capture_output=True,
            text=True,
            cwd=project_dir
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception as e:
        print(f"Warning: Could not get Git commit hash: {e}")
    return "unknown"

def increment_version_patch(project_dir):
    """Increment VERSION_PATCH in Config.h"""
    config_path = Path(project_dir) / "src" / "Config.h"

    try:
        with open(config_path, 'r') as f:
            content = f.read()

        # Find current VERSION_PATCH
        match = re.search(r'#define VERSION_PATCH (\d+)', content)
        if match:
            current_patch = int(match.group(1))
            new_patch = current_patch + 1

            # Replace VERSION_PATCH
            new_content = re.sub(
                r'#define VERSION_PATCH \d+',
                f'#define VERSION_PATCH {new_patch}',
                content
            )

            with open(config_path, 'w') as f:
                f.write(new_content)

            print(f"[Pre-build] Incremented VERSION_PATCH: {current_patch} -> {new_patch}")
            return new_patch
    except Exception as e:
        print(f"[Pre-build] Warning: Could not increment VERSION_PATCH: {e}")

    return None

def generate_git_version_header(project_dir, commit_hash):
    """Generate GitVersion.h with commit hash"""
    src_path = Path(project_dir) / "src"
    git_version_path = src_path / "GitVersion.h"

    header_content = f"""// Auto-generated file - DO NOT EDIT
// Generated by prebuild.py

#ifndef GIT_VERSION_H
#define GIT_VERSION_H

#define GIT_COMMIT_HASH "{commit_hash}"

#endif
"""

    try:
        with open(git_version_path, 'w') as f:
            f.write(header_content)
        print(f"[Pre-build] Generated GitVersion.h with commit hash: {commit_hash}")
    except Exception as e:
        print(f"[Pre-build] Warning: Could not generate GitVersion.h: {e}")

def pre_build_action(source, target, env):
    """Called by PlatformIO before the build"""
    print("\n=== Pre-build Version Management ===")

    project_dir = env['PROJECT_DIR']

    # Get Git commit hash
    commit_hash = get_git_commit_hash(project_dir)
    print(f"[Pre-build] Current commit hash: {commit_hash}")

    # Increment VERSION_PATCH
    increment_version_patch(project_dir)

    # Generate GitVersion.h
    generate_git_version_header(project_dir, commit_hash)

    print("=== Pre-build complete ===\n")

# Register the pre-build script to run before compilation
env.AddPreAction("$BUILD_DIR/src/light-saber.cpp.o", pre_build_action)
